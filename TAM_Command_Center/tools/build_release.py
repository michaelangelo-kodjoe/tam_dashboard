"""Build the TAM Command Center release zip (spec sections 4, 47, 53, 56; PM D-25c).

Usage:
  python tools/build_release.py [--channel prod|dev] [--out DIR] [--version X]

* prod (default): VERSION.txt is rewritten to channel=prod. This is the Windows release.
* dev: a DEV-preview package (channel=dev, includes db/seed_mock.py + mock_data.json
  so Launch_DEV_Preview.bat works). Never deploy it as production.

Fail-closed rules: refuses to build if web/ is missing or contains mock_data.json,
or if any database file (*.db, *.db-wal, *.db-shm, *.sqlite*), dev_data/, .venv or
node_modules would be shipped. Writes BUILD_MANIFEST.txt (SHA-256 of every other
file in the archive) inside the zip, plus <zip>.sha256 next to it.
Stdlib only. Set SOURCE_DATE_EPOCH for a reproducible timestamp.
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import os
import sys
import zipfile
from pathlib import Path

APP = Path(__file__).resolve().parent.parent
TOP = "TAM_Command_Center"

BANNED_PARTS = {".venv", "node_modules", "dev_data", "__pycache__", ".pytest_cache", "frontend", ".git", ".DS_Store"}
BANNED_SUFFIX = (".db", ".db-wal", ".db-shm", ".sqlite", ".sqlite3", ".pyc", ".log", ".lock")
TEST_ONLY_PINS = {"pytest", "httpx", "httpcore", "certifi", "iniconfig", "pluggy", "pygments"}  # test-client only
# uvicorn[standard] extras: optional, not needed for a loopback HTTP app, and websockets>=17 needs Python 3.11
# while the product supports 3.10 (found by the smoke test on 3.10). uvloop has no Windows wheels.
OPTIONAL_EXTRAS = {"uvloop", "httptools", "watchfiles", "websockets", "python-dotenv", "pyyaml"}
CRLF_FILES = (".bat", "README.txt", "VALIDATION.txt")

ROOT_FILES = [
    "Launch_TAM_Command_Center.bat", "Launch_DEV_Preview.bat", "Install_Dependency.bat",
    "Check_PROD_Environment.bat", "Check_DEV_Environment.bat",
    "README.txt", "VALIDATION.txt", "CHANGELOG.md", "TAM_PROJECT_STATE.md",
]
TOOLS_SHIPPED = ["tools/_resolve_python.bat", "tools/env_check.py", "tools/open_when_ready.py"]


def read_kv(p: Path) -> dict:
    out = {}
    for line in p.read_text(encoding="utf-8").splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1)
            out[k.strip().lower()] = v.strip()
    return out


def requirements(src: Path) -> str:
    """Pinned runtime requirements: the server requirements minus test-only pins and the
    optional uvicorn[standard] extras (see OPTIONAL_EXTRAS).
    httpx/pytest and their dependencies are tests-only. If a needed transitive pin
    were dropped, the smoke test (fresh venv + server start) would fail."""
    keep = ["# TAM Command Center runtime requirements (pinned; generated by tools/build_release.py).",
            "# Source: server/requirements.txt minus test-only packages and optional uvicorn extras. BLPAPI is NOT listed:",
            "# it is workstation-specific and must come from the Bloomberg-provided package.",
            "# openpyxl is not needed yet (Operations bulk upload / export are deferred phases)."]
    for line in src.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        name = s.split("==")[0].strip().lower().replace("_", "-")
        if name in TEST_ONLY_PINS or name in OPTIONAL_EXTRAS:
            continue
        keep.append(s)
    return "\n".join(keep) + "\n"


def collect(channel: str) -> list[str]:
    files: list[str] = []
    for p in sorted((APP / "server").glob("*.py")):
        files.append(f"server/{p.name}")
    db = APP / "db"
    for rel in ["migrate.py", "schema.sql"]:
        files.append(f"db/{rel}")
    files += sorted(f"db/migrations/{p.name}" for p in (db / "migrations").glob("*.sql"))
    files += sorted(f"db/queries/{p.name}" for p in (db / "queries").glob("*.sql"))
    if channel == "dev":
        files += ["db/seed_mock.py", "db/mock_data.json"]
    web = APP / "web"
    if not (web / "index.html").is_file():
        raise SystemExit("REFUSED: web/index.html missing. Run: cd frontend && npm run build:api")
    for p in sorted(web.rglob("*")):
        if p.is_file():
            files.append(p.relative_to(APP).as_posix())
    files += ROOT_FILES + TOOLS_SHIPPED
    guides = APP / "docs" / "guides"
    if guides.is_dir():
        files += sorted(p.relative_to(APP).as_posix() for p in guides.rglob("*") if p.is_file())
    return files


def guard(files: list[str], channel: str) -> None:
    for f in files:
        parts = set(Path(f).parts)
        if parts & BANNED_PARTS or f.lower().endswith(BANNED_SUFFIX):
            raise SystemExit(f"REFUSED: banned path would be shipped: {f}")
        if not (APP / f).is_file():
            raise SystemExit(f"REFUSED: expected file is missing: {f}")
        if Path(f).name == "mock_data.json" and channel != "dev":
            raise SystemExit(f"REFUSED: {f} must not ship in a prod release")
    if channel == "prod" and any(Path(f).name in ("seed_mock.py", "mock_data.json") for f in files):
        raise SystemExit("REFUSED: DEV seed data in a prod release")


def payload(rel: str, channel: str, version: str, ts: str) -> bytes:
    if rel == "VERSION.txt":
        validation = "UNVALIDATED (not production-ready until validated on the target Bloomberg Windows environment)"
        return (f"version={version}\nchannel={channel}\nbuilt_utc={ts}\nvalidation={validation}\n").encode("ascii")
    if rel == "requirements.txt":
        return requirements(APP / "server" / "requirements.txt").encode("ascii")
    data = (APP / rel).read_bytes()
    if rel.endswith(CRLF_FILES) or Path(rel).name in CRLF_FILES:
        data = data.replace(b"\r\n", b"\n").replace(b"\n", b"\r\n")
    return data


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--channel", choices=("prod", "dev"), default="prod")
    ap.add_argument("--out", default=str(APP / "dist"))
    ap.add_argument("--version")
    args = ap.parse_args()

    src_ver = read_kv(APP / "VERSION.txt").get("version", "0.0.0")
    version = args.version or src_ver
    epoch = int(os.environ.get("SOURCE_DATE_EPOCH", "0")) or None
    now = dt.datetime.fromtimestamp(epoch, dt.timezone.utc) if epoch else dt.datetime.now(dt.timezone.utc)
    ts = now.strftime("%Y-%m-%dT%H:%M:%SZ")

    files = collect(args.channel)
    all_rel = files + ["VERSION.txt", "requirements.txt"]
    guard(files, args.channel)
    all_rel = sorted(set(all_rel))

    entries: dict[str, bytes] = {rel: payload(rel, args.channel, version, ts) for rel in all_rel}
    if args.channel == "prod" and b"channel=prod" not in entries["VERSION.txt"]:
        raise SystemExit("REFUSED: VERSION.txt rewrite failed")
    manifest_lines = [
        "TAM Command Center - BUILD_MANIFEST.txt",
        f"version={version}  channel={args.channel}  built_utc={ts}",
        "Format: SHA-256  bytes  path   (every shipped file except this manifest; sha256sum -c compatible after removing the header)",
        "NOT production-ready until validated on the target Bloomberg Windows environment (see VALIDATION.txt).",
        "",
    ]
    for rel in all_rel:
        manifest_lines.append(f"{hashlib.sha256(entries[rel]).hexdigest()}  {len(entries[rel])}  {rel}")
    entries["BUILD_MANIFEST.txt"] = ("\r\n".join(manifest_lines) + "\r\n").encode("ascii")

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    suffix = "" if args.channel == "prod" else "_DEVPREVIEW"
    zpath = out / f"TAM_Command_Center_{version}_win{suffix}.zip"
    zt = (max(now.year, 1980), now.month, now.day, now.hour, now.minute, now.second)
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for rel in sorted(entries):
            zi = zipfile.ZipInfo(f"{TOP}/{rel}", date_time=zt)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, entries[rel])
    digest = hashlib.sha256(zpath.read_bytes()).hexdigest()
    (out / (zpath.name + ".sha256")).write_text(f"{digest}  {zpath.name}\n", encoding="ascii")
    print(f"built {zpath}  ({zpath.stat().st_size} bytes, {len(entries)} files)")
    print(f"zip sha256 {digest}")
    print(f"channel={args.channel} version={version}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
